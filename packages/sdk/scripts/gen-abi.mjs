// Regenerates src/abi.ts from the Foundry build (contracts/out) and the vendored,
// verified Pons v2 ABIs in scripts/pons/. Run after `forge build`:
//   node packages/sdk/scripts/gen-abi.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', '..', '..', 'contracts', 'out');
const pons = join(here, 'pons');

const clasp = {
  claspFactoryAbi: 'ClaspFactory',
  claspVaultAbi: 'ClaspVault',
  claspRouterAbi: 'ClaspRouter',
  claspLauncherAbi: 'ClaspLauncher',
};

// Pons fragments Clasp's contracts, indexer, keeper and website use. Errors are kept
// in full so reverts decode to names.
const ponsPick = {
  ponsFactoryAbi: {
    file: 'factory',
    names: [
      'getLaunchedToken', 'transferCreatorFeeRecipient', 'setBuybackEnabled', 'launchFee', 'launchEnabled',
      'getLaunchConfig', 'launchConfigCount', 'maxCreatorTaxBps', 'previewLaunchEconomics',
      'pendingCreatorFeeRecipient', 'executeCreatorFeeRecipientChange', 'CREATOR_FEE_RECIPIENT_TIMELOCK',
      'CREATOR_FEE_RECIPIENT_EXECUTION_WINDOW', 'feeEscrow', 'memeHook', 'poolManager', 'graduate',
      'createGraduatedPool', 'owner', 'TokenLaunched', 'CreatorFeeRecipientUpdated',
      'CreatorFeeRecipientChangeProposed', 'CreatorFeeRecipientChangeCancelled', 'LaunchSwept', 'PoolGraduated',
      'BuybackEnabledUpdated',
    ],
  },
  ponsFeeEscrowAbi: { file: 'escrow', names: ['balanceOf', 'claim', 'Credited', 'Claimed'] },
  ponsCurveAbi: {
    file: 'curve',
    names: [
      'getReserves', 'quoteReserve', 'tokenReserve', 'realQuoteReserve', 'sellableTokens', 'reservedTokens',
      'graduated', 'readyToGraduate', 'feeBps', 'creatorTaxBps', 'graduationThreshold', 'launchSupply',
      'launchedAt', 'phantomQuote', 'currentSnipeTaxBps', 'token', 'deployer', 'quoteFeeBalance',
      'creatorTaxBalance', 'buybackQuoteBalance', 'CurveBuy', 'CurveSell', 'FeesSwept', 'CurveCompleted',
    ],
  },
  ponsMemeHookAbi: {
    file: 'hook',
    names: [
      'launches', 'pendingFees', 'pendingCreatorTax', 'pendingBuyback', 'hookFeeBps', 'feeSweepOperator',
      'HookFeeCollected', 'PoolFeesSwept',
    ],
  },
  ponsTokenAbi: {
    file: 'token',
    names: [
      'name', 'symbol', 'decimals', 'totalSupply', 'balanceOf', 'allowance', 'approve', 'transfer',
      'transferFrom', 'logo', 'description', 'socials', 'getTokenInfo', 'deployer', 'curve', 'Transfer', 'Approval',
    ],
  },
};

const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const sections = [];

for (const [exportName, contract] of Object.entries(clasp)) {
  const abi = read(join(out, `${contract}.sol`, `${contract}.json`)).abi;
  sections.push(`export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;`);
}

for (const [exportName, { file, names }] of Object.entries(ponsPick)) {
  const full = read(join(pons, `${file}.abi.json`));
  const wanted = new Set(names);
  const abi = full.filter((item) => item.type === 'error' || wanted.has(item.name));
  const found = new Set(abi.map((item) => item.name));
  const missing = names.filter((n) => !found.has(n));
  if (missing.length) throw new Error(`${exportName}: missing ${missing.join(', ')}`);
  sections.push(`export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;`);
}

const header = `// GENERATED by scripts/gen-abi.mjs from contracts/out and scripts/pons/*.abi.json.
// Do not edit by hand: change the Solidity, run \`forge build\`, then \`node scripts/gen-abi.mjs\`.
`;
writeFileSync(join(here, '..', 'src', 'abi.ts'), `${header}\n${sections.join('\n\n')}\n`);
console.log(`wrote src/abi.ts (${sections.length} ABIs)`);
